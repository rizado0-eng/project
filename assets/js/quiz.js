var state = { segment:null, graph:null, nodeId:null, path:[], answers:[] };

var segmentSelect = document.getElementById('quizSegmentSelect');
var quizBody = document.getElementById('quizBody');
var quizProgress = document.getElementById('quizProgressBar');

function letterOf(i){ return ['А','Б','В','Г','Д','Е','Ж','З','И','К','Л'][i] || (i+1); }

function renderNode(){
  var graph = state.graph;
  var node = graph.nodes[state.nodeId];
  var progressPct = Math.min((state.path.length / graph.maxDepth) * 100, 96);
  quizProgress.style.width = progressPct + '%';

  var html = '<div class="quiz-question">' + node.q + '</div><div class="quiz-options">';
  node.options.forEach(function(opt, i){
    html += '<button type="button" class="quiz-option" data-next="' + opt.next + '" data-label="' + opt.t.replace(/"/g,'&quot;') + '">' +
      '<span class="letter">' + letterOf(i) + '</span><span>' + opt.t + '</span></button>';
  });
  html += '</div>';
  if (state.path.length > 0){
    html += '<button type="button" class="quiz-back" id="quizBackBtn"><svg class="icon" viewBox="0 0 24 24" width="14" height="14"><path d="M15 6l-6 6 6 6"/></svg>Назад</button>';
  }
  quizBody.innerHTML = html;

  quizBody.querySelectorAll('.quiz-option').forEach(function(btn){
    btn.addEventListener('click', function(){
      state.path.push(state.nodeId);
      state.answers.push({ q:node.q, a:btn.getAttribute('data-label') });
      var next = btn.getAttribute('data-next');
      if (next === 'RESULT'){
        renderResult();
      } else {
        state.nodeId = next;
        renderNode();
      }
    });
  });
  var backBtn = document.getElementById('quizBackBtn');
  if (backBtn){
    backBtn.addEventListener('click', function(){
      state.nodeId = state.path.pop();
      state.answers.pop();
      renderNode();
    });
  }
}

function renderResult(){
  quizProgress.style.width = '100%';
  console.log('Кредитный ДНК — ответы клиента:', state.segment, state.answers);
  quizBody.innerHTML =
    '<div class="quiz-result">' +
      '<div class="icon-wrap"><svg class="icon" viewBox="0 0 24 24" width="30" height="30"><path d="M20 6L9 17l-5-5"/></svg></div>' +
      '<h3>Портрет заявки готов</h3>' +
      '<p>Мы учли сумму, цель и вашу ситуацию с кредитной историей. Оставьте телефон — персональный менеджер подберёт конкретные банки и озвучит реальную ставку по вашему профилю.</p>' +
      '<a href="index.html#apply" class="btn btn-primary">Получить консультацию</a>' +
    '</div>';
}

if (segmentSelect){
  segmentSelect.querySelectorAll('[data-segment]').forEach(function(card){
    card.addEventListener('click', function(){
      var seg = card.getAttribute('data-segment');
      state.segment = seg;
      state.graph = GRAPHS[seg];
      state.nodeId = state.graph.start;
      state.path = [];
      state.answers = [];
      segmentSelect.style.display = 'none';
      quizBody.style.display = 'block';
      document.getElementById('quizProgressWrap').style.display = 'block';
      renderNode();
    });
  });
}

